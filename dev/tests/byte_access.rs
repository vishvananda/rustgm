#[test]
fn byte_access_matches_independently_declared_objects() -> Result<(), Box<dyn std::error::Error>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("root")?;
    let out = root.join(format!(
        "obj/parallel/pa27/byte-access-source-{}",
        std::process::id()
    ));
    std::fs::create_dir_all(&out)?;
    for &(name, path, rust, frontend, reason) in CASES {
        checked::check_views_with_rustc_args(
            &root.join(path),
            &out,
            name,
            rust,
            &[
                ("--emit-types", frontend),
                ("--emit-lowir", frontend),
                ("--emit-constants", frontend),
            ],
            reason,
            &["--cap-lints=allow"],
        )?;
    }
    Ok(())
}
#[test]
#[ignore = "requires pinned rustc and CPPGM backend"]
fn byte_access_literal_native_storage_and_relocations() -> Result<(), Box<dyn std::error::Error>> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .ok_or("root")?;
    let names = [
        "scalar-first-byte",
        "scalar-u16-read",
        "scalar-byte-index",
        "scalar-word-index",
        "scalar-byte-store",
        "scalar-offset-store",
        "unaligned-array-read",
        "unaligned-array-write",
        "record-second-field",
        "record-offset-store",
        "nested-logical-offset",
        "physical-subobject-cast",
        "field-pointer-roundtrip",
        "shared-reconstruction",
        "mutable-reconstruction",
        "float-bits",
        "bool-valid",
        "char-valid",
        "pointer-word-reinterpret",
        "cast-array-base-offset",
        "oversized-record-prefix",
        "oversized-array-prefix",
        "published-reference",
        "published-field-reference",
        "packed-logical-base",
        "packed-field-unaligned-read",
        "reinterpret-aggregate-reference-cast",
        "offset-unaligned-read",
        "zst-read-isolated",
        "offset-pointer-word-reinterpret",
        "counted-byte-cast-copy",
        "byte-offset-fill",
        "byte-offset-copy",
        "reference-field-demand",
        "reference-nested-field-demand",
        "runtime-published-offset",
        "runtime-published-reference",
        "runtime-cast-write",
        "native-reference-referent",
        "native-reference-lifetime",
        "runtime-byte-index",
    ];
    let mut owned = Vec::new();
    for name in names {
        let (_, path, _, _, _) = CASES
            .iter()
            .find(|case| case.0 == name)
            .ok_or("native case")?;
        owned.push((name, std::fs::read_to_string(root.join(path))?));
    }
    let cases: Vec<_> = owned
        .iter()
        .map(|(name, text)| (*name, text.as_str(), false))
        .collect();
    native::check_literal_cases("parallel/pa27/byte-access-native", &cases)
}
