//! Edition-2024 strict and reserved words. Weak words remain contextual.
use super::token::Kind;

#[must_use]
pub fn identifier(kind: Kind, name: &str) -> bool {
    match kind {
        Kind::Identifier => !reserved(name),
        Kind::RawIdentifier => !matches!(name, "_" | "self" | "Self" | "super" | "crate"),
        _ => false,
    }
}

#[must_use]
pub fn reserved(name: &str) -> bool {
    matches!(
        name,
        "_" | "as"
            | "async"
            | "await"
            | "break"
            | "const"
            | "continue"
            | "crate"
            | "dyn"
            | "else"
            | "enum"
            | "extern"
            | "false"
            | "fn"
            | "for"
            | "if"
            | "impl"
            | "in"
            | "let"
            | "loop"
            | "match"
            | "mod"
            | "move"
            | "mut"
            | "pub"
            | "ref"
            | "return"
            | "self"
            | "Self"
            | "static"
            | "struct"
            | "super"
            | "trait"
            | "true"
            | "type"
            | "unsafe"
            | "use"
            | "where"
            | "while"
            | "abstract"
            | "become"
            | "box"
            | "do"
            | "final"
            | "gen"
            | "macro"
            | "override"
            | "priv"
            | "try"
            | "typeof"
            | "unsized"
            | "virtual"
            | "yield"
    )
}
